"""Store for runs, polls, sightings and events: PostgreSQL, or SQLite for tests and quick local use.

Store("data/sources.sqlite") opens SQLite; Store("postgresql://user:pass@host:5432/db") opens
PostgreSQL through psycopg 3. The SQL is written once, with ? placeholders, and means the same
on both: text sorts byte by byte (timestamps are ISO-8601 text in UTC), duplicate sightings are
skipped with ON CONFLICT DO NOTHING, and ids come from an identity column.
"""

from __future__ import annotations

import json
import re
import sqlite3
import threading
from contextlib import contextmanager
from pathlib import Path
from typing import Any, Iterable, Mapping

try:  # only needed for PostgreSQL
    import psycopg
    from psycopg.rows import dict_row
except ImportError:  # pragma: no cover - depends on what is installed
    psycopg = None
    dict_row = None

from .models import Filing
from .sources.base import PollResult
from .timeutil import to_iso, utcnow

SCHEMA = """
CREATE TABLE IF NOT EXISTS runs (
    id INTEGER PRIMARY KEY AUTOINCREMENT,
    started_at TEXT NOT NULL,
    sources TEXT NOT NULL,
    settings TEXT
);
CREATE TABLE IF NOT EXISTS polls (
    id INTEGER PRIMARY KEY AUTOINCREMENT,
    run_id INTEGER NOT NULL REFERENCES runs(id),
    source TEXT NOT NULL,
    started_at TEXT NOT NULL,
    finished_at TEXT,
    status INTEGER,
    elapsed_ms REAL,
    wire_bytes INTEGER,
    body_bytes INTEGER,
    not_modified INTEGER NOT NULL DEFAULT 0,
    item_count INTEGER NOT NULL DEFAULT 0,
    new_count INTEGER NOT NULL DEFAULT 0,
    newest_published_at TEXT,
    build_time TEXT,
    error TEXT
);
CREATE INDEX IF NOT EXISTS polls_run_source ON polls(run_id, source, started_at);
CREATE TABLE IF NOT EXISTS sightings (
    id INTEGER PRIMARY KEY AUTOINCREMENT,
    run_id INTEGER NOT NULL REFERENCES runs(id),
    source TEXT NOT NULL,
    exchange TEXT NOT NULL,
    source_id TEXT NOT NULL,
    match_key TEXT NOT NULL,
    company TEXT,
    company_key TEXT,
    symbol TEXT,
    isin TEXT,
    subject TEXT,
    headline TEXT,
    attachment_url TEXT,
    published_at TEXT,
    filed_at TEXT,
    detected_at TEXT NOT NULL,
    backlog INTEGER NOT NULL DEFAULT 0,
    company_id TEXT,
    event_type TEXT,
    event_id INTEGER,
    UNIQUE (run_id, source, source_id)
);
CREATE INDEX IF NOT EXISTS sightings_run_key ON sightings(run_id, match_key);
CREATE INDEX IF NOT EXISTS sightings_exchange_item ON sightings(exchange, source_id);
CREATE TABLE IF NOT EXISTS events (
    id INTEGER PRIMARY KEY AUTOINCREMENT,
    company_id TEXT NOT NULL,
    isin TEXT,
    nse_symbol TEXT,
    bse_code TEXT,
    company TEXT,
    event_type TEXT NOT NULL,
    type_exchange TEXT,
    session_date TEXT NOT NULL,
    in_market_hours INTEGER NOT NULL DEFAULT 0,
    news_time TEXT,
    first_seen_at TEXT,
    first_source TEXT,
    first_run_id INTEGER,
    copies INTEGER NOT NULL DEFAULT 1,
    sources TEXT,
    exchanges TEXT,
    status TEXT NOT NULL DEFAULT 'new',
    backlog INTEGER NOT NULL DEFAULT 0,
    created_at TEXT NOT NULL,
    updated_at TEXT NOT NULL
);
CREATE INDEX IF NOT EXISTS events_company_session ON events(company_id, session_date);
"""

# Columns added after the first release; older databases get them on open.
SIGHTING_MIGRATIONS = {"company_id": "TEXT", "event_type": "TEXT", "event_id": "INTEGER"}
EVENT_MIGRATIONS = {"type_exchange": "TEXT"}
EVENT_COLUMNS = (
    "company_id", "isin", "nse_symbol", "bse_code", "company", "event_type", "type_exchange", "session_date",
    "in_market_hours", "news_time", "first_seen_at", "first_source", "first_run_id", "copies",
    "sources", "exchanges", "status", "backlog",
)


TABLES = ("runs", "polls", "sightings", "events")  # in an order that keeps references valid
CONNECT_TIMEOUT_S = 10  # fail fast on a wrong address rather than hang for minutes
POSTGRES_DRIVER_MISSING = 'PostgreSQL needs the psycopg driver: py -m pip install "psycopg[binary]"'
Row = Mapping[str, Any]


def is_postgres_url(target: str | Path) -> bool:
    return str(target).startswith(("postgresql://", "postgres://"))


def describe_target(target: str | Path) -> str:
    """The database to show in messages: a file's full path, or a URL without its password."""
    if is_postgres_url(target):
        return re.sub(r"://([^:/@]+):[^@]*@", r"://\1:***@", str(target))
    return str(Path(target).resolve()) if str(target) != ":memory:" else ":memory:"


def _pg_type(kind: str) -> str:
    return {"TEXT": 'TEXT COLLATE "C"', "INTEGER": "BIGINT"}.get(kind, kind)


def _pg_schema(schema: str) -> str:
    """The SQLite schema in PostgreSQL types. COLLATE "C" sorts text byte by byte, like SQLite."""
    s = schema.replace("INTEGER PRIMARY KEY AUTOINCREMENT", "BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY")
    s = re.sub(r"\b(run_id|event_id|first_run_id) INTEGER\b", r"\1 BIGINT", s)
    s = re.sub(r"\bREAL\b", "DOUBLE PRECISION", s)
    return re.sub(r"\bTEXT\b", 'TEXT COLLATE "C"', s)


def _statements(script: str) -> list[str]:
    return [statement.strip() for statement in script.split(";") if statement.strip()]


class Store:
    """Runs, polls, sightings and events, in SQLite (a file or ":memory:") or PostgreSQL (a URL).

    One connection is shared by the poller's threads; every call takes self._lock, and each
    write is one transaction.
    """

    def __init__(self, target: str | Path) -> None:
        target = str(target)
        self.target = target
        self.dialect = "postgres" if is_postgres_url(target) else "sqlite"
        self._lock = threading.Lock()
        if self.dialect == "postgres":
            if psycopg is None:
                raise RuntimeError(POSTGRES_DRIVER_MISSING)
            self._conn = psycopg.connect(target, autocommit=True, row_factory=dict_row, connect_timeout=CONNECT_TIMEOUT_S)
            schema = _pg_schema(SCHEMA)
        else:
            if target != ":memory:":
                Path(target).parent.mkdir(parents=True, exist_ok=True)
            self._conn = sqlite3.connect(target, check_same_thread=False)
            self._conn.row_factory = sqlite3.Row
            schema = SCHEMA
        with self._lock, self._tx():
            # Older databases lack columns added since: add them, then the index that uses them.
            for statement in _statements(schema):
                self._run(statement)
            for table, migrations in (("sightings", SIGHTING_MIGRATIONS), ("events", EVENT_MIGRATIONS)):
                existing = set(self._column_list(table))
                for column, kind in migrations.items():
                    if column not in existing:
                        kind = _pg_type(kind) if self.dialect == "postgres" else kind
                        self._run(f"ALTER TABLE {table} ADD COLUMN {column} {kind}")
            self._run("CREATE INDEX IF NOT EXISTS sightings_event ON sightings(event_id)")

    # Plumbing: the only place that knows which database this is ---------------------
    @contextmanager
    def _tx(self):
        """One transaction, committed at the end or rolled back on error. Callers hold self._lock."""
        if self.dialect == "postgres":
            with self._conn.transaction():
                yield
        else:
            with self._conn:
                yield

    def _run(self, sql: str, params: Iterable = ()):
        if self.dialect == "postgres":
            params = tuple(params)
            return self._conn.execute(sql.replace("?", "%s"), params if params else None)
        return self._conn.execute(sql, tuple(params))

    def _run_many(self, sql: str, rows: list[tuple]) -> None:
        if not rows:
            return
        if self.dialect == "postgres":
            with self._conn.cursor() as cursor:
                cursor.executemany(sql.replace("?", "%s"), rows)
        else:
            self._conn.executemany(sql, rows)

    def _insert_id(self, sql: str, params: Iterable) -> int:
        if self.dialect == "postgres":
            return int(self._run(sql + " RETURNING id", params).fetchone()["id"])
        return int(self._run(sql, params).lastrowid)

    def _column_list(self, table: str) -> list[str]:
        if self.dialect == "postgres":
            rows = self._run(
                "SELECT column_name AS name FROM information_schema.columns "
                "WHERE table_schema = current_schema() AND table_name = ? ORDER BY ordinal_position",
                (table,),
            ).fetchall()
        else:
            rows = self._run(f"PRAGMA table_info({table})").fetchall()
        return [row["name"] for row in rows]

    def column_names(self, table: str) -> list[str]:
        with self._lock:
            return self._column_list(table)

    def count(self, table: str) -> int:
        if table not in TABLES:
            raise ValueError(f"unknown table {table}")
        return int(self._query(f"SELECT COUNT(*) AS n FROM {table}")[0]["n"])

    def close(self) -> None:
        with self._lock:
            self._conn.close()

    # Writes ------------------------------------------------------------------------
    def start_run(self, sources: Iterable[str], settings: dict | None = None) -> int:
        with self._lock, self._tx():
            return self._insert_id(
                "INSERT INTO runs (started_at, sources, settings) VALUES (?, ?, ?)",
                (to_iso(utcnow()), ",".join(sources), json.dumps(settings or {})),
            )

    def record_poll(self, run_id: int, result: PollResult, new_count: int) -> None:
        newest = max((f.published_at for f in result.filings if f.published_at), default=None)
        with self._lock, self._tx():
            self._run(
                """INSERT INTO polls (run_id, source, started_at, finished_at, status, elapsed_ms,
                       wire_bytes, body_bytes, not_modified, item_count, new_count,
                       newest_published_at, build_time, error)
                   VALUES (?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?)""",
                (
                    run_id,
                    result.source,
                    to_iso(result.started_at),
                    to_iso(result.finished_at),
                    result.status,
                    result.elapsed_ms,
                    result.wire_bytes,
                    result.body_bytes,
                    int(result.not_modified),
                    len(result.filings),
                    new_count,
                    to_iso(newest),
                    to_iso(result.build_time),
                    result.error,
                ),
            )

    def record_sightings(self, run_id: int, filings: Iterable[Filing], detected_at, backlog: bool) -> int:
        rows = [
            (
                run_id,
                f.source,
                f.exchange,
                f.source_id,
                f.match_key,
                f.company,
                f.company_key,
                f.symbol,
                f.isin,
                f.subject,
                f.headline,
                f.attachment_url,
                to_iso(f.published_at),
                to_iso(f.filed_at),
                to_iso(detected_at),
                int(backlog),
            )
            for f in filings
        ]
        if not rows:
            return 0
        sql = """INSERT INTO sightings (run_id, source, exchange, source_id, match_key,
                     company, company_key, symbol, isin, subject, headline, attachment_url,
                     published_at, filed_at, detected_at, backlog)
                 VALUES (?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?)
                 ON CONFLICT DO NOTHING"""
        with self._lock, self._tx():
            return sum(max(self._run(sql, row).rowcount, 0) for row in rows)

    # Events ------------------------------------------------------------------------
    def get_event(self, event_id: int) -> Row | None:
        rows = self._query("SELECT * FROM events WHERE id = ?", (event_id,))
        return rows[0] if rows else None

    def linked_event(self, exchange: str, source_id: str) -> Row | None:
        """The event an earlier sighting of this exact item (same exchange, file and timestamp) belongs to."""
        rows = self._query(
            """SELECT e.* FROM sightings s JOIN events e ON e.id = s.event_id
               WHERE s.exchange = ? AND s.source_id = ? ORDER BY s.id LIMIT 1""",
            (exchange, source_id),
        )
        return rows[0] if rows else None

    def find_events(self, company_id: str, session_date: str) -> list[Row]:
        return self._query(
            "SELECT * FROM events WHERE company_id = ? AND session_date = ? ORDER BY id", (company_id, session_date)
        )

    def create_event(self, **fields) -> int:
        unknown = set(fields) - set(EVENT_COLUMNS)
        if unknown:
            raise ValueError(f"unknown event fields: {sorted(unknown)}")
        now = to_iso(utcnow())
        columns = [*fields, "created_at", "updated_at"]
        with self._lock, self._tx():
            return self._insert_id(
                f"INSERT INTO events ({', '.join(columns)}) VALUES ({', '.join('?' for _ in columns)})",
                (*fields.values(), now, now),
            )

    def update_event(self, event_id: int, **fields) -> None:
        unknown = set(fields) - set(EVENT_COLUMNS)
        if unknown:
            raise ValueError(f"unknown event fields: {sorted(unknown)}")
        assignments = ", ".join(f"{name} = ?" for name in fields)
        with self._lock, self._tx():
            self._run(
                f"UPDATE events SET {assignments}, updated_at = ? WHERE id = ?",
                (*fields.values(), to_iso(utcnow()), event_id),
            )

    def set_sighting_events(self, run_id: int, links: list[tuple[str, str, int, str, str]]) -> None:
        """links: (source, source_id, event_id, company_id, event_type)."""
        if not links:
            return
        with self._lock, self._tx():
            self._run_many(
                """UPDATE sightings SET event_id = ?, company_id = ?, event_type = ?
                   WHERE run_id = ? AND source = ? AND source_id = ?""",
                [(event_id, company_id, event_type, run_id, source, source_id)
                 for source, source_id, event_id, company_id, event_type in links],
            )

    def clear_events(self, from_run: int | None = None) -> None:
        """Delete events and unlink sightings, for all runs or for one run and every later run.

        Later runs go too because their sightings can belong to events an earlier run created.
        """
        with self._lock, self._tx():
            if from_run is None:
                self._run("DELETE FROM events")
                self._run("UPDATE sightings SET event_id = NULL, company_id = NULL, event_type = NULL")
            else:
                self._run("DELETE FROM events WHERE first_run_id >= ?", (from_run,))
                self._run(
                    "UPDATE sightings SET event_id = NULL, company_id = NULL, event_type = NULL WHERE run_id >= ?",
                    (from_run,),
                )

    def event_copies(self, event_id: int) -> list[Row]:
        """Every sighting linked to an event, in the order they were seen."""
        return self._query("SELECT * FROM sightings WHERE event_id = ? ORDER BY detected_at, id", (event_id,))

    def events(self, run_id: int | None = None) -> list[Row]:
        if run_id is None:
            return self._query("SELECT * FROM events ORDER BY news_time, id")
        return self._query("SELECT * FROM events WHERE first_run_id = ? ORDER BY news_time, id", (run_id,))

    # Reads -------------------------------------------------------------------------
    def _query(self, sql: str, params: tuple = ()) -> list[Row]:
        with self._lock:
            return list(self._run(sql, params).fetchall())

    def runs(self) -> list[Row]:
        return self._query("SELECT * FROM runs ORDER BY id")

    def run(self, run_id: int) -> Row | None:
        rows = self._query("SELECT * FROM runs WHERE id = ?", (run_id,))
        return rows[0] if rows else None

    def latest_run_id(self) -> int | None:
        rows = self._query("SELECT MAX(id) AS id FROM runs")
        return rows[0]["id"] if rows and rows[0]["id"] is not None else None

    def polls(self, run_id: int) -> list[Row]:
        return self._query("SELECT * FROM polls WHERE run_id = ? ORDER BY started_at, id", (run_id,))

    def sightings(self, run_id: int) -> list[Row]:
        return self._query("SELECT * FROM sightings WHERE run_id = ? ORDER BY detected_at, id", (run_id,))


def copy_database(source: Store, target: Store, replace: bool = False) -> dict[str, int]:
    """Copy every table from one store to another, keeping ids, in one transaction.

    The target must be empty unless replace is set, which empties it first. Returns the row
    count of each table in the target afterwards.
    """
    if not replace:
        filled = {table: target.count(table) for table in TABLES if target.count(table)}
        if filled:
            raise ValueError(f"the target already has rows: {filled}")
    plan = []
    for table in TABLES:
        wanted = set(target.column_names(table))
        columns = [c for c in source.column_names(table) if c in wanted]
        rows = source._query(f"SELECT {', '.join(columns)} FROM {table} ORDER BY id")
        plan.append((table, columns, [tuple(row[c] for c in columns) for row in rows]))
    with target._lock, target._tx():
        if replace:
            for table in reversed(TABLES):
                target._run(f"DELETE FROM {table}")
        for table, columns, rows in plan:
            target._run_many(
                f"INSERT INTO {table} ({', '.join(columns)}) VALUES ({', '.join('?' for _ in columns)})", rows)
        if target.dialect == "postgres":  # carry on numbering after the copied ids
            for table in TABLES:
                target._run(f"SELECT setval(pg_get_serial_sequence('{table}', 'id'), "
                            f"COALESCE((SELECT MAX(id) FROM {table}), 0) + 1, false)")
    return {table: target.count(table) for table in TABLES}
